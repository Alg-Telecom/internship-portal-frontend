/**
 * Minimal, dependency-free translation dictionary. No i18next — npm install
 * isn't possible on this machine right now (C: drive is full), so this is a
 * nested key -> string tree per language, flattened once into dot-path
 * lookups (see flatten() below) and read through useLanguage()'s t('a.b.c').
 *
 * Only UI chrome lives here — labels, buttons, headers, statuses, messages.
 * Anything a user typed (their name, a team description an admin wrote, a
 * file name, notes, ...) is real data and is never routed through t().
 */
